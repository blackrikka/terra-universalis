#!/usr/bin/env python3
"""빅토리아 특수 프로젝트 (사양서 80). 원본 게임의 '특수 프로젝트' 파일이 없어서 임시로 디시전(시간 걸리는 프로젝트)으로 만든다.
    스팀 나이트 재건  -> 초중장갑 대대 편제 해금 (TU_VIC_steam_heavy)
    고속 육상전함      -> 철도포 확장 이동포대 'Dreadnought' (TU_VIC_dreadnought). 웰링턴 충성도 60+ 또는 산업 헌장 중점으로 해금
    모범군             -> 아슬란 루트의 정예 보병 (TU_VIC_exemplars). 중점 '모범군 개편' 뒤에 열린다
각 프로젝트: 정치력 + 기간 (days_remove). 끝나면 편제 잠금 해제 + 수도에 사단 1개. 편제는 history/units/VIC_1097.txt 에 잠긴 채 들어 있다.
사용법 (python -I):  python -I tools/vic_projects.py
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MOD = REPO / "terra_universalis"
sys.path.insert(0, str(REPO / "tools"))

# id, 편제, 한국어, 영어, 설명 ko, en, 정치력, 일수, 보이는 조건, 사용 조건, 사단 수
PROJECTS = [
    ("steam", "TU_VIC_steam_heavy", "스팀 나이트 재건", "Rebuild the Steam Knights",
     "옛 스팀 나이트의 증기 갑주를 다시 짓는다. 끝나면 초중장갑 대대 편제(보병 4 + 경전차 4)를 쓸 수 있고 한 개가 수도에 선다.",
     "Rebuild the old Steam Knight armour. When done the heavy battalion template becomes available and one division is raised at the capital.",
     150, 240, "has_completed_focus = TU_VIC_steam_knight_formation", "", 1),
    ("dread", "TU_VIC_dreadnought", "고속 육상전함 'Dreadnought'", "Fast Landship 'Dreadnought'",
     "철도포를 얹어 길게 늘린 이동포대형 육상전함. 웰링턴 공작의 충성도가 60 이상이거나 산업 헌장 중점을 마쳐야 열린다.",
     "A landship stretched with railway guns into a mobile battery. Needs Wellington loyalty of 60+ or the Industry Charter focus.",
     200, 300, "has_completed_focus = TU_VIC_eco_industry_charter",
     "OR = { has_completed_focus = TU_VIC_eco_industry_charter check_variable = { TU_VIC_loyalty_wellington > 59 } }", 1),
    ("exem", "TU_VIC_exemplars", "모범군 창설", "Raise the Exemplars",
     "아슬란 복위군의 정예 '모범군'을 세운다. 보병 8, 경전차 1, 포병 2의 편제. 두 개 사단이 수도에 선다.",
     "Raise the Aslan restoration's elite Exemplars: infantry 8, light armour 1, artillery 2. Two divisions muster at the capital.",
     120, 180, "has_country_flag = TU_VIC_route_asl", "has_country_flag = TU_VIC_exemplars_unlocked", 2),
]


def decisions():
    out = ["# generated by tools/vic_projects.py (spec 80)", "TU_VIC_projects_category = {"]
    out = ["# generated by tools/vic_projects.py (spec 80)", "TU_VIC_projects_category = {"]
    for pid, tpl, ko, en, dk, de, pp, days, vis, av, n in PROJECTS:
        avail = ("\t\tavailable = {\n\t\t\t%s\n\t\t}\n" % av) if av else ""
        out.append("""	TU_VIC_proj_%(pid)s = {
		icon = GFX_decision_generic_military
		allowed = { original_tag = VIC }
		visible = {
			%(vis)s
			NOT = { has_country_flag = TU_VIC_proj_%(pid)s_done }
		}
%(avail)s		cost = %(pp)d
		days_remove = %(days)d
		fire_only_once = yes
		complete_effect = { hidden_effect = { set_country_flag = TU_VIC_proj_%(pid)s_run } }
		remove_effect = {
			clr_country_flag = TU_VIC_proj_%(pid)s_run
			set_country_flag = TU_VIC_proj_%(pid)s_done
			set_division_template_lock = { division_template = "%(tpl)s" is_locked = no }
			capital_scope = { create_unit = { division = "division_template = \\"%(tpl)s\\" start_experience_factor = 0.5 start_equipment_factor = 1" owner = VIC count = %(n)d } }
			army_experience = 20
		}
		ai_will_do = { base = 0 }
	}
""" % dict(pid=pid, tpl=tpl, vis=vis, avail=avail, pp=pp, days=days, n=n))
    out.append("}\n")
    return "\n".join(out)


def loc():
    ko = ["l_korean:", " # generated by tools/vic_projects.py (spec 80)",
          ' TU_VIC_projects_category:0 "특수 프로젝트"',
          ' TU_VIC_projects_category_desc:0 "빅토리아의 비밀 병기 프로젝트. 정치력을 들여 시작하면 정해진 기간 뒤 편제가 열리고 사단이 선다."']
    en = ["l_english:", " # generated by tools/vic_projects.py (spec 80)",
          ' TU_VIC_projects_category:0 "Special Projects"',
          ' TU_VIC_projects_category_desc:0 "Victoria\'s secret weapon projects. Pay political power; after the set time the template unlocks and the division musters."']
    for pid, tpl, k, e, dk, de, *_ in PROJECTS:
        ko += [' TU_VIC_proj_%s:0 "%s"' % (pid, k), ' TU_VIC_proj_%s_desc:0 "%s"' % (pid, dk)]
        en += [' TU_VIC_proj_%s:0 "%s"' % (pid, e), ' TU_VIC_proj_%s_desc:0 "%s"' % (pid, de)]
        ko.append(' %s:0 "%s"' % (tpl, k.replace("재건", "").replace("창설", "").strip() or k))
        en.append(' %s:0 "%s"' % (tpl, e))
    return "\n".join(ko) + "\n", "\n".join(en) + "\n"


def oob():
    p = MOD / "history" / "units" / "VIC_1097.txt"
    t = p.read_text(encoding="utf-8-sig")
    add = "".join("""
division_template = {
	name = "%s"
	division_names_group = TU_DIVNAMES_FALLBACK
	is_locked = yes

	regiments = {
		infantry = { x = 0 y = 0 }
	}
}
""" % tpl for _, tpl, *_ in PROJECTS if 'name = "%s"' % tpl not in t)
    if add:
        i = t.index("\nunits = {")
        p.write_text(t[:i] + add + t[i:], encoding="utf-8")
    import templates
    templates.apply_file(p)


def main():
    (MOD / "common" / "decisions" / "categories" / "tu_vic_projects_categories.txt").write_text(
        "# generated by tools/vic_projects.py (spec 80)\nTU_VIC_projects_category = {\n\ticon = GFX_decision_category_generic_political_actions\n"
        "\tallowed = { original_tag = VIC }\n\tpriority = 98\n}\n", encoding="utf-8")
    d = decisions().replace("TU_VIC_projects_category = {", "TU_VIC_projects_category = {", 1)
    (MOD / "common" / "decisions" / "tu_vic_projects_decisions.txt").write_text(d, encoding="utf-8")
    ko, en = loc()
    (MOD / "localisation" / "korean" / "tu_vic_projects_l_korean.yml").write_bytes(ko.encode("utf-8-sig"))
    (MOD / "localisation" / "english" / "tu_vic_projects_l_english.yml").write_bytes(en.encode("utf-8-sig"))
    oob()
    print("VIC_PROJECTS %d" % len(PROJECTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
