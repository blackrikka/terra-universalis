#!/usr/bin/env python3
"""국가 고유 장치 패널 (사양서 22): 디시전 분류 위에 변수 막대와 수치를 보여 주는 scripted GUI.

사용법:  python -I tools/guigen/build_panels.py

만드는 파일
    common/scripted_guis/tu_panels.txt          패널마다 scripted_gui (context_type = decision_category)
    interface/tu_panels.gui                      패널 창 (줄마다 이름 · 칸 막대 · 수치)
    interface/tu_panels.gfx, gfx/interface/tu/*.dds   막대 칸 그림 (빈 칸 + 색 5가지, 이 스크립트가 그린다)
    localisation/{korean,english}/tu_panels_l_*.yml
패널은 각 나라의 첫 디시전 분류(content_lib 가 scripted_gui 줄을 넣는다)와 육상함 분류에 붙는다.
막대: 칸 수 = min(최대값, 10). 칸 k 는 변수가 최대값의 (k+1)/칸수 이상이면 채워진다.
"""

import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
MOD = REPO / "terra_universalis"
sys.path.insert(0, str(REPO / "tools" / "mapgen"))
from dds import write_dds  # noqa: E402

COLORS = {"green": (92, 184, 92), "red": (210, 72, 60), "gold": (230, 180, 60), "blue": (80, 150, 220),
          "purple": (160, 100, 200)}
SEG_W, SEG_H, SEG_GAP = 24, 12, 3
ROW_H, TOP = 28, 12
LABEL_X, BAR_X, VAL_X = 14, 170, 350
WIDTH = 470          # 디시전 칸 너비에 맞춘다 (넘치면 오른쪽이 잘린다)

# 패널 id: [(변수, 최대, 색, 한국어, 영어)]. 나라별 수치는 디시전 탭 패널로 옮겼다 (tools/gauges, 사양서 39)
PANELS = {
    "LANDSHIP": [("TU_landships", 6, "gold", "취역한 육상함", "Landships Commissioned")],
}


def draw_textures():
    out = MOD / "gfx" / "interface" / "tu"
    out.mkdir(parents=True, exist_ok=True)

    def seg(rgb, path):
        a = np.zeros((SEG_H, SEG_W, 4), np.uint8)
        a[:, :, :3] = rgb
        a[:, :, 3] = 255
        a[0, :, :3] = np.minimum(np.array(rgb) + 50, 255)         # 위 밝은 선
        a[-1, :, :3] = np.array(rgb) // 2                          # 아래 어두운 선
        a[:, 0, :3] = a[:, -1, :3] = np.array(rgb) // 2
        write_dds(out / path, a)

    seg((45, 42, 36), "seg_empty.dds")
    for name, rgb in COLORS.items():
        seg(rgb, "seg_%s.dds" % name)
    gfx = ["# Generated by tools/guigen/build_panels.py", "spriteTypes = {"]
    for name in ["empty"] + list(COLORS):
        gfx.append('\tspriteType = {\n\t\tname = "GFX_tu_seg_%s"\n\t\ttexturefile = "gfx/interface/tu/seg_%s.dds"\n\t}' % (name, name))
    gfx.append("}")
    (MOD / "interface" / "tu_panels.gfx").write_text("\n".join(gfx) + "\n", encoding="utf-8")


def thresholds(mx):
    n = min(mx, 10)
    return [mx * (k + 1) / n for k in range(n)]


# 염국 내전(용의 시대) 현황판: 12형제 세력마다 이름 · 지도자 · 상태
SIBLINGS = ["YCH", "YLI", "YWA", "YDU", "YSH", "YNI", "YJN", "YJE", "YJI", "YYI", "YFA", "YYU"]
STATES = [  # (이름, 색, 한국어, 영어, 조건) 위에서부터 먼저 맞는 것
    ("gone", "empty", "없음", "None", "NOT = { country_exists = %s }"),
    ("freed", "green", "해방", "Freed", "%s = { has_country_flag = TU_YAN_fac_freed }"),
    ("subject", "blue", "복속", "Subject", "%s = { is_subject_of = YAN }"),
    ("war", "red", "교전 중", "At War", "%s = { has_war_with = YAN }"),
    ("free", "gold", "독립", "Independent", "always = yes"),
]


def dragon_war(gui, sg, ko, en):
    win = "TU_DRAGONWAR_panel_window"
    elems, trig = [], []
    for i, tag in enumerate(SIBLINGS):
        y = TOP + i * 24
        elems.append("""		instantTextBoxType = {
			name = "tu_dw_name_%d"
			position = { x = 14 y = %d }
			font = "hoi_16mbs"
			text = "TU_DW_NAME_%s"
			maxWidth = 150
			maxHeight = 20
			format = left
		}
		instantTextBoxType = {
			name = "tu_dw_leader_%d"
			position = { x = 170 y = %d }
			font = "hoi_16mbs"
			text = "TU_DW_LEADER_%s"
			maxWidth = 170
			maxHeight = 20
			format = left
		}""" % (i, y, tag, i, y, tag))
        ko += [("TU_DW_NAME_%s" % tag, "[%s.GetNameDef]" % tag), ("TU_DW_LEADER_%s" % tag, "[%s.GetLeader]" % tag)]
        en += [("TU_DW_NAME_%s" % tag, "[%s.GetNameDef]" % tag), ("TU_DW_LEADER_%s" % tag, "[%s.GetLeader]" % tag)]
        prev = []
        for st, col, sko, sen, cond in STATES:
            elems.append("""		iconType = {
			name = "tu_dw_%s_icon_%d"
			spriteType = "GFX_tu_seg_%s"
			position = { x = 345 y = %d }
		}
		instantTextBoxType = {
			name = "tu_dw_%s_text_%d"
			position = { x = 377 y = %d }
			font = "hoi_16mbs"
			text = "TU_DW_STATE_%s"
			maxWidth = 85
			maxHeight = 20
			format = left
		}""" % (st, i, col, y + 3, st, i, y, st.upper()))
            c = cond % tag if "%s" in cond else cond
            body = " ".join(["NOT = { %s }" % x for x in prev] + [c])
            trig.append("\t\t\ttu_dw_%s_icon_%d_visible = { %s }" % (st, i, body))
            trig.append("\t\t\ttu_dw_%s_text_%d_visible = { %s }" % (st, i, body))
            prev.append(c)
    for st, col, sko, sen, cond in STATES:
        ko.append(("TU_DW_STATE_%s" % st.upper(), sko))
        en.append(("TU_DW_STATE_%s" % st.upper(), sen))
    height = TOP + len(SIBLINGS) * 24 + 10
    gui.append("""	containerWindowType = {
		name = "%s"
		position = { x = 0 y = 0 }
		size = { width = %d height = %d }
		background = {
			name = "Background"
			quadTextureSprite = "GFX_tiled_window_2b_border"
		}

%s
	}""" % (win, WIDTH, height, "\n".join(elems)))
    sg.append("""	TU_DRAGONWAR_panel = {
		context_type = decision_category
		window_name = "%s"
		visible = {
			YAN = { has_country_flag = TU_YAN_age_of_dragons }
		}
		triggers = {
%s
		}
	}""" % (win, "\n".join(trig)))


def main():
    draw_textures()
    sg, gui, ko, en = [], [], [], []
    dragon_war(gui, sg, ko, en)
    for pid, rows in PANELS.items():
        win = "TU_%s_panel_window" % pid
        elems, trig = [], []
        for i, (var, mx, col, lko, len_) in enumerate(rows):
            y = TOP + i * ROW_H
            key = "TU_%s_panel_%d" % (pid, i)
            ko += [(key, lko), (key + "_val", "[?%s|0] / %d" % (var, mx))]
            en += [(key, len_), (key + "_val", "[?%s|0] / %d" % (var, mx))]
            elems.append("""		instantTextBoxType = {
			name = "tu_label_%d"
			position = { x = %d y = %d }
			font = "hoi_16mbs"
			text = "%s"
			maxWidth = 190
			maxHeight = 20
			format = left
		}""" % (i, LABEL_X, y, key))
            for k, th in enumerate(thresholds(mx)):
                x = BAR_X + k * (SEG_W + SEG_GAP)
                elems.append("""		iconType = {
			name = "tu_seg_bg_%d_%d"
			spriteType = "GFX_tu_seg_empty"
			position = { x = %d y = %d }
		}
		iconType = {
			name = "tu_seg_%d_%d"
			spriteType = "GFX_tu_seg_%s"
			position = { x = %d y = %d }
		}""" % (i, k, x, y + 3, i, k, col, x, y + 3))
                trig.append("\t\t\ttu_seg_%d_%d_visible = { check_variable = { %s > %s } }" % (i, k, var, round(th - 0.001, 3)))
            elems.append("""		instantTextBoxType = {
			name = "tu_val_%d"
			position = { x = %d y = %d }
			font = "hoi_16mbs"
			text = "%s_val"
			maxWidth = 80
			maxHeight = 20
			format = left
		}""" % (i, VAL_X, y, key))
        height = TOP + len(rows) * ROW_H + 8
        gui.append("""	containerWindowType = {
		name = "%s"
		position = { x = 0 y = 0 }
		size = { width = %d height = %d }
		background = {
			name = "Background"
			quadTextureSprite = "GFX_tiled_window_2b_border"
		}

%s
	}""" % (win, WIDTH, height, "\n".join(elems)))
        vis = "original_tag = %s" % pid if pid != "LANDSHIP" else "has_tech = tu_landship_1"
        sg.append("""	TU_%s_panel = {
		context_type = decision_category
		window_name = "%s"
		visible = {
			%s
		}
		triggers = {
%s
		}
	}""" % (pid, win, vis, "\n".join(trig)))
    (MOD / "common" / "scripted_guis").mkdir(parents=True, exist_ok=True)
    (MOD / "common" / "scripted_guis" / "tu_panels.txt").write_text(
        "# Generated by tools/guigen/build_panels.py: country mechanic panels on decision categories.\nscripted_gui = {\n%s\n}\n"
        % "\n\n".join(sg), encoding="utf-8")
    (MOD / "interface" / "tu_panels.gui").write_text(
        "# Generated by tools/guigen/build_panels.py\nguiTypes = {\n%s\n}\n" % "\n\n".join(gui), encoding="utf-8")
    for lang, items in (("korean", ko), ("english", en)):
        body = "l_%s:\n" % lang + "".join(' %s:0 "%s"\n' % kv for kv in items)
        (MOD / "localisation" / lang / ("tu_panels_l_%s.yml" % lang)).write_bytes(("\ufeff" + body).encode("utf-8"))
    for p in (MOD / "common/scripted_guis/tu_panels.txt", MOD / "interface/tu_panels.gui", MOD / "interface/tu_panels.gfx"):
        s = p.read_text(encoding="utf-8")
        assert s.count("{") == s.count("}") and all(ord(c) < 128 for c in s), p
    print("PANELS %d, rows %d" % (len(PANELS), sum(len(r) for r in PANELS.values())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
