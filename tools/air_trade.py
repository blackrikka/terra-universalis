#!/usr/bin/env python3
"""항공 수입 (사양서 64).

바다를 쓸 수 없어 해외 무역(호송선)이 막혀 있다. 대신 수송 비행선으로 자원을 실어 온다.
모든 나라에 디시전 분류 '항공 수입'을 만든다. 자원마다 대상 디시전 하나 (대상 = 그 자원을 파는 나라).

    조건  수송 비행선(transport_plane_equipment) PLANES 대 이상, 대상과 전쟁 중이 아님
    비용  정치력 COST
    효과  계약 기간 DAYS 일 동안
          - 수도 주에 그 자원 +AMOUNT (계약이 끝나면 되돌린다. 주 변수 TU_air_<자원> 으로 센다)
          - 민간 공장 1개를 계약에 쓴다 (실제 무역과 같은 값: 자원 8 = 민간 공장 1)
          - 수송 비행선 PLANES 대가 묶인다. 끝나면 RETURN 대가 돌아온다 (나머지는 운항 손실)
          - 파는 나라는 정치력 +EXPORTER_PP
    같은 자원이라도 대상 나라가 다르면 계약을 여러 개 맺을 수 있다 (수송기만 있으면).

파는 나라: tools/mapgen/resources.py 의 산지 (AMOUNTS). 오리론(steel)은 모든 나라가 판다.
사용법 (python -I):  python -I tools/air_trade.py
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
MOD = REPO / "terra_universalis"
sys.path.insert(0, str(REPO / "tools" / "mapgen"))
from resources import AMOUNTS, KEYS  # noqa: E402
from tiers import TIERS  # noqa: E402

PLANES, RETURN, AMOUNT, DAYS, COST, EXPORTER_PP = 10, 8, 8, 180, 25, 15
NAMES = {"oil": ("오리지늄", "Originium"), "steel": ("오리론", "Oriron"), "rubber": ("폴리에스테르", "Polyester"),
         "aluminium": ("아케톤", "Aketon"), "tungsten": ("망간", "Manganese"), "chromium": ("장치", "Device")}
CAT = "TU_air_trade_category"


def sellers(key):
    if key == "steel":
        return sorted(TIERS)
    return sorted(t for t, a in AMOUNTS.items() if a.get(key))


def decision(key):
    did = "TU_air_import_%s" % key
    tags = " ".join("tag = %s" % t for t in sellers(key))
    return """	%(did)s = {
		icon = GFX_decision_generic_air
		allowed = { always = yes }

		target_trigger = {
			FROM = {
				NOT = { tag = ROOT }
				exists = yes
				OR = { %(tags)s }
			}
		}

		visible = {
			has_tech = early_transport_plane
		}

		available = {
			has_equipment = { transport_plane_equipment > %(pm1)d }
			NOT = { has_war_with = FROM }
			FROM = { NOT = { has_war_with = ROOT } }
		}

		cost = %(cost)d
		fire_only_once = no
		days_remove = %(days)d

		modifier = {
			civilian_factory_use = 1
		}

		complete_effect = {
			add_equipment_to_stockpile = { type = transport_plane_equipment amount = -%(planes)d }
			capital_scope = {
				add_resource = { type = %(key)s amount = %(amount)d }
				add_to_variable = { TU_air_%(key)s = %(amount)d }
			}
			FROM = { add_political_power = %(pp)d }
		}

		remove_effect = {
			add_equipment_to_stockpile = { type = transport_plane_equipment amount = %(ret)d }
			random_owned_state = {
				limit = { check_variable = { TU_air_%(key)s > %(am1)d } }
				add_resource = { type = %(key)s amount = -%(amount)d }
				add_to_variable = { TU_air_%(key)s = -%(amount)d }
			}
		}

		ai_will_do = {
			base = 1
			modifier = {
				factor = 0
				has_equipment = { transport_plane_equipment < %(ai)d }
			}
		}
	}
""" % dict(did=did, tags=tags, pm1=PLANES - 1, cost=COST, days=DAYS, planes=PLANES, key=key, amount=AMOUNT,
           pp=EXPORTER_PP, ret=RETURN, am1=AMOUNT - 1, ai=PLANES * 3)


def main():
    (MOD / "common" / "decisions" / "categories" / "tu_air_trade_categories.txt").write_text(
        "# generated by tools/air_trade.py (spec 64)\n%s = {\n\ticon = GFX_decision_category_generic_trade\n"
        "\tallowed = { always = yes }\n\tvisible = { has_tech = early_transport_plane }\n\tpriority = 90\n}\n" % CAT,
        encoding="utf-8")
    body = "# generated by tools/air_trade.py (spec 64): air imports by transport airship\n%s = {\n%s}\n" % (
        CAT, "\n".join(decision(k) for k in KEYS))
    (MOD / "common" / "decisions" / "tu_air_trade_decisions.txt").write_text(body, encoding="utf-8")
    ko = ["l_korean:",
          ' %s:0 "항공 수입"' % CAT,
          ' %s_desc:0 "바다를 건널 수 없으니 하늘로 실어 온다. 수송 비행선 §Y%d§!대와 민간 공장 1개를 %d일 동안 계약에 쓰면 '
          '수도에 자원 §G+%d§!이 들어온다. 계약이 끝나면 수송 비행선 %d대가 돌아온다."' % (CAT, PLANES, DAYS, AMOUNT, RETURN)]
    en = ["l_english:",
          ' %s:0 "Air Imports"' % CAT,
          ' %s_desc:0 "We cannot cross the sea, so we fly it in. Commit §Y%d§! transport airships and one civilian factory for %d days '
          'to bring §G+%d§! of a resource to the capital. %d airships return when the contract ends."' % (CAT, PLANES, DAYS, AMOUNT, RETURN)]
    for k in KEYS:
        nk, ne = NAMES[k]
        did = "TU_air_import_%s" % k
        ko += [' %s:0 "%s 항공 수입: [From.GetName]"' % (did, nk),
               ' %s_desc:0 "[From.GetName]에서 %s을(를) 수송 비행선으로 실어 온다. %d일 동안 %s §G+%d§!, 민간 공장 1개 사용, '
               '수송 비행선 %d대 투입 (끝나면 %d대 귀환). [From.GetName]은(는) 정치력 +%d."'
               % (did, nk, DAYS, nk, AMOUNT, PLANES, RETURN, EXPORTER_PP)]
        en += [' %s:0 "%s Airlift: [From.GetName]"' % (did, ne),
               ' %s_desc:0 "Fly %s in from [From.GetName]. For %d days: %s §G+%d§!, one civilian factory used, '
               '%d transport airships committed (%d return). [From.GetName] gains %d political power."'
               % (did, ne.lower(), DAYS, ne, AMOUNT, PLANES, RETURN, EXPORTER_PP)]
    for lang, lines in (("korean", ko), ("english", en)):
        (MOD / "localisation" / lang / ("tu_air_trade_l_%s.yml" % lang)).write_bytes(("\n".join(lines) + "\n").encode("utf-8-sig"))
    print("AIR_TRADE decisions=%d" % len(KEYS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
