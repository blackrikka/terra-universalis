#!/usr/bin/env python3
"""오퍼레이터 클래스의 역할을 대대 능력치로 맞추고 고유 대대를 만든다 (사양서 61).

사용법 (python -I):  python -I tools/unit_widths.py 다음에  python -I tools/unit_roles.py

ROLES 의 값을 대대 블록의 맨 위 항목으로 넣거나 바꾼다. soft_attack 같은 공격·방어 값은 장비 능력치에 더하는 배율이다
(recon 의 soft_attack = -0.9 는 -90%). 파일은 unit_widths.py 가 만든 복사본을 쓰고, 없으면 reference/vanilla_units 에서 가져온다.
tu_arts_caster 는 바닐라 대전차 대대를 바탕으로 새 파일을 만든다.
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "reference" / "vanilla_units"
OUT = REPO / "terra_universalis" / "common" / "units"
GFX = REPO / "terra_universalis" / "interface" / "tu_units.gfx"
sys.stdout.reconfigure(encoding="utf-8")

ROLES = {
    "recon.txt": {
        "recon": {"recon": 1.5, "initiative": 0.05},          # 뱅가드: 전선 선점, 주도권
        "mot_recon": {"recon": 2, "initiative": 0.05},
    },
    "infantry.txt": {
        "motorized": {"breakthrough": 0.1},
        "mechanized": {"breakthrough": 0.1},
        "infantry": {"soft_attack": 0.15, "max_organisation": 65},     # 가드: 주력 딜러
        "mountaineers": {"soft_attack": 0.2},
        "marine": {"soft_attack": 0.2},
        "paratrooper": {"breakthrough": 0.15},                # 스페셜리스트: 후방 침투
    },
    "medium_armor.txt": {"medium_armor": {"defense": 0.2, "armor_value": 0.05, "maximum_speed": -0.1}},   # 디펜더: 튼튼하고 느림
    "heavy_armor.txt": {"heavy_armor": {"defense": 0.25, "armor_value": 0.05, "maximum_speed": -0.1}},
    "artillery_brigade.txt": {"artillery_brigade": {"soft_attack": 0.1}},       # 스나이퍼: 대인 광역 타격
    "anti-air_brigade.txt": {"anti_air_brigade": {"air_attack": 0.2}},          # 스나이퍼: 공중 차단
    "anti_tank_brigade.txt": {                                                  # 캐스터: 높은 관통력
        "anti_tank_brigade": {"ap_attack": 0.15},
        "mot_anti_tank_brigade": {"ap_attack": 0.15},
    },
    "field_hospital.txt": {"field_hospital": {"casualty_trickleback": 0.3}},    # 메딕: 인력 보존
    "signal.txt": {"signal_company": {"initiative": 0.15}},                     # 서포터: 작전 계획 가속
    "logistics.txt": {"logistics_company": {"supply_consumption_factor": -0.15}},
    "military_police.txt": {"military_police": {"suppression_factor": 0.3}},    # 스페셜리스트: 후방 안정
}


def block(text, name):
    m = re.search(r"^\t%s\s*=\s*\{" % re.escape(name), text, re.M)
    if not m:
        raise SystemExit("대대 없음: %s" % name)
    j = text.index("{", m.start())
    d, k = 0, j
    while True:
        c = text[k]
        d += (c == "{") - (c == "}")
        k += 1
        if d == 0:
            return m.start(), k


def set_stat(body, key, value, nl):
    """대대 블록의 맨 위 항목(탭 두 개)만 바꾼다. 없으면 combat_width 뒤에 넣는다."""
    pat = re.compile(r"^(\t\t%s\s*=\s*)[^\s#]+" % re.escape(key), re.M)
    if pat.search(body):
        return pat.sub(lambda m: m.group(1) + str(value), body, count=1)
    m = re.search(r"^\t\tcombat_width\s*=[^\r\n]*\r?\n", body, re.M)
    if not m:
        raise SystemExit("combat_width 없음")
    return body[:m.end()] + "\t\t%s = %s%s" % (key, value, nl) + body[m.end():]


def read(name):
    p = OUT / name if (OUT / name).is_file() else SRC / name
    return p.read_bytes().decode("utf-8-sig")


def apply_roles():
    for name, units in ROLES.items():
        text = read(name)
        nl = "\r\n" if "\r\n" in text else "\n"
        for unit, stats in units.items():
            for key, value in stats.items():
                a, b = block(text, unit)
                text = text[:a] + set_stat(text[a:b], key, value, nl) + text[b:]
        (OUT / name).write_bytes(text.encode("utf-8"))
        print("%s: %s" % (name, ", ".join(units)))


def make_caster():
    src = (SRC / "anti_tank_brigade.txt").read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
    a, b = block(src, "anti_tank_brigade")
    body = src[a:b].replace("\tanti_tank_brigade = {", "\ttu_arts_caster = {", 1)
    body = body.replace('abbreviation = "ANT"', 'abbreviation = "ACS"').replace("active = yes", "active = no")
    body = body.replace("priority = 1197", "priority = 1196")
    body = body.replace("anti_tank_equipment = 36", "anti_tank_equipment = 36\n\t\t\tsupport_equipment = 12")
    for key, value in (("combat_width", 2), ("manpower", 750), ("training_time", 150), ("supply_consumption", 0.15),
                       ("soft_attack", 1), ("hard_attack", 0.1), ("ap_attack", 0.25)):
        body = set_stat(body, key, value, "\n")
    (OUT / "tu_arts_caster.txt").write_text(
        "# Generated by tools/unit_roles.py (spec 61)\nsub_units = {\n\n%s\n}\n" % body, encoding="utf-8")
    GFX.write_text("""# Generated by tools/unit_roles.py: the arts caster borrows the anti-tank icons until it has its own art
spriteTypes = {
	spriteType = { name = "GFX_unit_tu_arts_caster_icon_medium" textureFile = "gfx/interface/counters/divisions_large/unit_at_icon.dds" noOfFrames = 2 }
	spriteType = { name = "GFX_unit_tu_arts_caster_icon_medium_white" textureFile = "gfx/interface/counters/divisions_small/onmap_unit_at_icon.dds" noOfFrames = 2 }
	spriteType = { name = "GFX_unit_tu_arts_caster_icon_small" textureFile = "gfx/texticons/unit_anti_tank_icon_small.dds" }
}
""", encoding="utf-8")


if __name__ == "__main__":
    apply_roles()
    make_caster()
    print("UNIT_ROLES ok")
