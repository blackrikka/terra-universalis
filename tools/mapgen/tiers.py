#!/usr/bin/env python3
"""국가 체급별 시작 군대·공장·기술 (사양서 18).

사용법:  python -I tools/mapgen/tiers.py   (그다음 build_countries.py 를 다시 돌린다)

체급 (원작 비중 기준)
    S 열강      우르수스, 빅토리아, 염국, 컬럼비아
    A 지역 강국  라테라노, 카시미어, 라이타니엔, 사르곤, 카즈델
    B 중소국    이베리아, 시라쿠사, 극동, 미노스, 볼리바르, 림 빌리튼, 쉐라그, 용문
    C 소국      사미, 로도스 아일랜드
    (레유니온은 시작 땅이 없고, 쉐이 12국·황야는 내전/특수 태그라 빼둔다)

만드는 파일
    common/scripted_effects/tu_tier_effects.txt  TU_tier_<TAG>: 시작 때 공장을 짓고 사단을 만든다
        공장: 수도에 절반, 나머지는 인력이 큰 주 최대 3곳에 나눔. 주마다 필요한 만큼 공유 건설 슬롯을 늘린 뒤 즉시 건설.
              (지도 생성 때 모든 수도에 들어간 민간 2·군수 1 은 합계에 포함)
        사단: 수도에 절반, 나머지는 같은 주들에. 이미 시작 효과(TU_<TAG>_startup)로 사단을 만드는 나라는 모자란 만큼만.
    common/on_actions/tu_tier_on_actions.txt     on_startup 에서 위 효과를 부른다
    history/units/<TAG>_1097.txt                 OOB 가 없는 나라: 체급별 보병 사단 틀
    tools/mapgen/tier_history/<TAG>.txt          build_countries 가 history/countries 에 붙인다:
                                                 oob, 연구 슬롯, 시작 기술
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MOD = REPO / "terra_universalis"
HIST = REPO / "tools" / "mapgen" / "tier_history"

# 태그: (체급, 민간 공장, 군수 공장, 사단)
TIERS = {
    "URS": ("S", 26, 18, 30), "VIC": ("S", 30, 16, 26), "YAN": ("S", 30, 16, 28), "COL": ("S", 32, 14, 22),
    "LAT": ("A", 16, 8, 14), "KAZ": ("A", 18, 8, 14), "LEI": ("A", 16, 8, 12), "SAR": ("A", 14, 10, 18),
    "KZD": ("A", 8, 12, 18),
    "IBE": ("B", 10, 4, 8), "SIR": ("B", 10, 4, 8), "HIG": ("B", 8, 5, 10), "MIN": ("B", 8, 3, 6),
    "BOL": ("B", 6, 4, 10), "RIM": ("B", 10, 4, 6), "KJE": ("B", 6, 3, 6), "LGM": ("B", 10, 3, 6),
    "SAM": ("C", 3, 2, 5), "RHO": ("C", 3, 2, 4),
}
BASE_CIV, BASE_MIL = 2, 1          # mapgen 이 모든 수도에 넣은 공장
# 이미 시작 효과로 사단을 만드는 나라: (만드는 수, 추가 사단에 쓸 틀)
EXISTING = {
    "URS": (8, "TU_URS_infantry"), "VIC": (12, "TU_VIC_line_infantry"), "KZD": (6, "TU_KZD_infantry"),
    "YAN": (10, "TU_YAN_infantry"), "LGM": (3, "TU_LGM_guard"), "RHO": (3, "TU_RHO_escort"),
}
RESEARCH_SLOTS = {"S": 4, "A": 3, "B": 3, "C": 2}
BASIC = ["infantry_weapons", "tech_support", "gw_artillery", "basic_train", "tu_oripathy_research"]
TECHS = {   # tools/techgen/build_techs.py 의 기술 id
    "C": BASIC + ["tech_engineers", "tech_recon"],
    "B": BASIC + ["infantry_weapons1", "tech_engineers", "tech_recon", "tech_field_hospital", "basic_machine_tools",
                  "construction1", "tu_arts_theory"],
    "A": BASIC + ["infantry_weapons1", "tech_engineers", "tech_recon", "tech_field_hospital", "basic_machine_tools",
                  "construction1", "tu_arts_theory", "interwar_artillery", "tech_trucks", "gwtank", "early_fighter",
                  "electronic_mechanical_engineering", "tu_ori_refining_1", "tu_landship_1"],
    "S": BASIC + ["infantry_weapons1", "tech_engineers", "tech_recon", "tech_field_hospital", "basic_machine_tools",
                  "construction1", "tu_arts_theory", "interwar_artillery", "tech_trucks", "motorised_infantry", "gwtank",
                  "early_fighter", "early_bomber", "electronic_mechanical_engineering", "tu_ori_refining_1", "tu_landship_1", "fuel_silos",
                  "excavation1"],
}
EXTRA_TECHS = {"LAT": ["tu_lat_firearms_1"], "RIM": ["tu_ori_refining_1"], "RHO": ["tu_suppressants", "tu_field_arts_medicine"]}
EXP = {"S": "0.3", "A": "0.3", "B": "0.2", "C": "0.2"}


def load_states():
    st = {}
    for f in (MOD / "history" / "states").glob("*.txt"):
        t = f.read_text(encoding="utf-8-sig")
        sid = int(re.search(r"\bid\s*=\s*(\d+)", t).group(1))
        o = re.search(r"\bowner\s*=\s*(\w+)", t)
        mp = int(re.search(r"\bmanpower\s*=\s*(\d+)", t).group(1))
        cat = re.search(r"state_category\s*=\s*(\w+)", t).group(1)
        st[sid] = dict(owner=o.group(1) if o else None, mp=mp, cat=cat)
    return st


def capitals():
    caps = {}
    for f in (MOD / "history" / "countries").glob("*.txt"):
        m = re.search(r"^capital\s*=\s*(\d+)", f.read_text(encoding="utf-8-sig"), re.M)
        if m:
            caps[f.name[:3]] = int(m.group(1))
    return caps


def split(total, n):
    """total 을 수도 절반 + 나머지 n-1 곳에 고르게."""
    if n == 1 or total <= 1:
        return [total] + [0] * (n - 1)
    cap = (total + 1) // 2
    rest = total - cap
    others = [rest // (n - 1) + (1 if i < rest % (n - 1) else 0) for i in range(n - 1)]
    return [cap] + others


def template_text(tag, tier):
    inf = 6 if tier in ("S", "A") else 4
    regs = "\n".join("\t\tinfantry = { x = %d y = %d }" % (i // 3, i % 3) for i in range(inf))
    if tier in ("S", "A"):
        regs += "\n\t\tartillery_brigade = { x = 2 y = 0 }"
    return """# %s starting army (generated by tools/mapgen/tiers.py, tier %s).
# Divisions are created by TU_tier_%s (tu_tier_effects.txt) on startup.

division_template = {
	name = "TU_%s_line_infantry"
	division_names_group = TU_DIVNAMES_FALLBACK

	regiments = {
%s
	}
	support = {
		engineer = { x = 0 y = 0 }
		recon = { x = 0 y = 1 }
	}
}

units = {
}
""" % (tag, tier, tag, tag, regs)


def main():
    st = load_states()
    caps = capitals()
    HIST.mkdir(exist_ok=True)
    effects = ["# Generated by tools/mapgen/tiers.py. Do not edit by hand.",
               "# Starting factories and divisions by country tier (spec 18). Country scope, called on startup.", ""]
    calls = []
    for tag, (tier, civ, mil, divs) in TIERS.items():
        cap = caps.get(tag)
        if cap is None:
            print("skip (no capital):", tag)
            continue
        own = sorted((s for s, d in st.items() if d["owner"] == tag and s != cap), key=lambda s: (-st[s]["mp"], s))
        places = [cap] + own[:3]
        civ_add = split(max(civ - BASE_CIV, 0), len(places))
        mil_add = split(max(mil - BASE_MIL, 0), len(places))
        made, tmpl = EXISTING.get(tag, (0, "TU_%s_line_infantry" % tag))
        div_add = split(max(divs - made, 0), len(places))
        body = []
        for s, c, m, d in zip(places, civ_add, mil_add, div_add):
            if not (c or m or d):
                continue
            lines = []
            if c + m:
                lines.append("add_extra_state_shared_building_slots = %d" % (c + m))
            if c:
                lines.append("add_building_construction = { type = industrial_complex level = %d instant_build = yes }" % c)
            if m:
                lines.append("add_building_construction = { type = arms_factory level = %d instant_build = yes }" % m)
            if d:
                lines.append('create_unit = { division = "division_template = \\"%s\\" start_experience_factor = %s '
                             'start_equipment_factor = 0.8" owner = %s count = %d }' % (tmpl, EXP[tier], tag, d))
            inner = "\n".join("\t\t\t" + l for l in lines)
            body.append("\tif = {\n\t\tlimit = { %d = { is_owned_and_controlled_by = ROOT } }\n\t\t%d = {\n%s\n\t\t}\n\t}"
                        % (s, s, inner))
        effects.append("# tier %s: %d civ, %d mil, %d divisions\nTU_tier_%s = {\n%s\n}\n" % (tier, civ, mil, divs, tag, "\n".join(body)))
        calls.append("\t\t\tif = { limit = { country_exists = %s } %s = { TU_tier_%s = yes } }" % (tag, tag, tag))

        oob = MOD / "history" / "units" / ("%s_1097.txt" % tag)
        hist = ["# %s: tier %s (generated by tools/mapgen/tiers.py, appended by build_countries.py)" % (tag, tier)]
        hist.append("set_research_slots = %d" % RESEARCH_SLOTS[tier])
        hist.append("set_technology = {\n%s\n}" % "\n".join("\t%s = 1" % t for t in TECHS[tier] + EXTRA_TECHS.get(tag, [])))
        if tag not in EXISTING:
            oob.write_text(template_text(tag, tier), encoding="utf-8")
            hist.append('oob = "%s_1097"' % tag)
        (HIST / ("%s.txt" % tag)).write_text("\n".join(hist) + "\n", encoding="utf-8")

    out = MOD / "common" / "scripted_effects" / "tu_tier_effects.txt"
    out.write_text("\n".join(effects), encoding="utf-8")
    (MOD / "common" / "on_actions" / "tu_tier_on_actions.txt").write_text(
        "# Generated by tools/mapgen/tiers.py: starting factories and divisions by tier.\non_actions = {\n\ton_startup = {\n"
        "\t\teffect = {\n"
        "\t\t\t# Once only (spec 40): on_startup can run again in multiplayer or on load; do not stack factories and divisions\n"
        "\t\t\tif = {\n\t\t\t\tlimit = { NOT = { has_global_flag = TU_tiers_applied } }\n\t\t\t\tset_global_flag = TU_tiers_applied\n"
        "%s\n\t\t\t}\n\t\t}\n\t}\n}\n" % "\n".join("\t\t" + c for c in calls), encoding="utf-8")
    for p in (out,):
        t = p.read_text()
        assert t.count("{") == t.count("}") and all(ord(c) < 128 for c in t)
    print("tiers:", len(calls), "countries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
