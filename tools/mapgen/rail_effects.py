#!/usr/bin/env python3
"""철도·요새 건설 스크립트 효과 만들기 (사양서 16: 철도 중점 / 요새 중점).

사용법:  python -I tools/mapgen/rail_effects.py
만드는 파일: terra_universalis/common/scripted_effects/tu_rail_fort_effects.txt
            terra_universalis/localisation/{korean,english}/tu_rail_fort_l_*.yml

TU_build_railway (국가 범위)
    시작 수도 주마다 블록 하나. 수도 주에서 그 나라 주요 도시 주(승점·인력 순, 자기 땅으로 이어진 주) 최대 RAIL_TARGETS 곳까지
    build_railway level 1 을 놓는다. 처음에는 철도를 새로 깔고, 다시 부르면 같은 노선의 레벨이 1씩 오른다.
    수도와 목표 주를 모두 자기가 장악하고 있을 때만 짓는다. 수도가 목록에 없으면 기반시설 1단계로 대신한다.
TU_build_forts_1/2/3, TU_build_coastal_forts_1/2/3 (국가 범위)
    국경 주(이웃 주 가운데 남의 땅이 있는 주) 1/2/3곳의 국경 프로빈스에 육상 요새 2/2/3단계.
    국경 주가 없으면 수도에. 해안 요새는 해안 주의 해안 프로빈스에 해안 요새.
"""

import csv
import re
import sys
from pathlib import Path

from PIL import Image
import numpy as np

REPO = Path(__file__).resolve().parents[2]
MOD = REPO / "terra_universalis"
OUT = MOD / "common" / "scripted_effects" / "tu_rail_fort_effects.txt"
RAIL_TARGETS = 4
SKIP_TAGS = {"WLD"}


def load_states():
    states = {}
    for f in (MOD / "history" / "states").glob("*.txt"):
        t = f.read_text(encoding="utf-8-sig")
        sid = int(re.search(r"\bid\s*=\s*(\d+)", t).group(1))
        owner = re.search(r"\bowner\s*=\s*(\w+)", t)
        mp = re.search(r"\bmanpower\s*=\s*(\d+)", t)
        vp = sum(int(v) for _, v in re.findall(r"victory_points\s*=\s*\{\s*(\d+)\s+(\d+)", t))
        provs = [int(x) for x in re.search(r"provinces\s*=\s*\{([^}]*)\}", t).group(1).split()]
        states[sid] = dict(owner=owner.group(1) if owner else None, mp=int(mp.group(1)) if mp else 0,
                           vp=vp, provs=provs)
    return states


def load_capitals():
    caps = {}
    for f in (MOD / "history" / "countries").glob("*.txt"):
        tag = f.name[:3]
        m = re.search(r"^capital\s*=\s*(\d+)", f.read_text(encoding="utf-8-sig"), re.M)
        if m and tag not in SKIP_TAGS:
            caps[tag] = int(m.group(1))
    return caps


def province_adjacency():
    land = set()
    colour = {}
    with open(MOD / "map" / "definition.csv", encoding="utf-8-sig") as fh:
        for row in csv.reader(fh, delimiter=";"):
            if len(row) < 5 or not row[0].isdigit():
                continue
            pid = int(row[0])
            colour[(int(row[1]), int(row[2]), int(row[3]))] = pid
            if row[4] == "land":
                land.add(pid)
    img = np.asarray(Image.open(MOD / "map" / "provinces.bmp").convert("RGB")).astype(np.int64)
    key = (img[:, :, 0] << 16) | (img[:, :, 1] << 8) | img[:, :, 2]
    lut = {(r << 16) | (g << 8) | b: p for (r, g, b), p in colour.items()}
    adj = set()
    for a, b in ((key[:, :-1], key[:, 1:]), (key[:-1, :], key[1:, :])):
        diff = a != b
        for x, y in set(zip(a[diff].tolist(), b[diff].tolist())):
            pa, pb = lut.get(x), lut.get(y)
            if pa is not None and pb is not None and pa in land and pb in land:
                adj.add((min(pa, pb), max(pa, pb)))
    return adj


def main():
    states = load_states()
    caps = load_capitals()
    p2s = {p: s for s, d in states.items() for p in d["provs"]}
    sadj = {s: set() for s in states}
    for a, b in province_adjacency():
        sa, sb = p2s.get(a), p2s.get(b)
        if sa and sb and sa != sb:
            sadj[sa].add(sb)
            sadj[sb].add(sa)

    blocks = []
    done = set()
    for tag in sorted(caps):
        cap = caps[tag]
        if cap in done or cap not in states:
            continue
        owner = states[cap]["owner"]
        own = {s for s, d in states.items() if d["owner"] == owner}
        # 수도에서 자기 땅으로 이어진 주
        seen, stack = {cap}, [cap]
        while stack:
            s = stack.pop()
            for t in sadj[s]:
                if t in own and t not in seen:
                    seen.add(t)
                    stack.append(t)
        cands = sorted(seen - {cap}, key=lambda s: (-states[s]["vp"], -states[s]["mp"], s))[:RAIL_TARGETS]
        if not cands:
            print("  no rail targets:", tag, cap)
            continue
        done.add(cap)
        lines = []
        for t in cands:
            lines.append("""		if = {
			limit = { %d = { is_controlled_by = ROOT } }
			build_railway = { level = 1 start_state = %d target_state = %d build_only_on_allied = yes }
		}""" % (t, cap, t))
        blocks.append((cap, owner, "\n".join(lines)))

    out = ["# Generated by tools/mapgen/rail_effects.py. Do not edit by hand.",
           "# Railway focuses: lay or upgrade railways from the starting capital to the main cities.",
           "# Fort focuses: build land forts on border provinces / coastal forts on coastal provinces.", "",
           "TU_build_railway = {", "\tcustom_effect_tooltip = TU_build_railway_tt", "\thidden_effect = {"]
    first = True
    for cap, owner, body in blocks:
        out.append("\t\t%s = {" % ("if" if first else "else_if"))
        out.append("\t\t\tlimit = { capital_scope = { state = %d } %d = { is_controlled_by = ROOT } }" % (cap, cap))
        out.append("\n".join("\t" + l for l in body.split("\n")))
        out.append("\t\t}")
        first = False
    out += ["\t\telse = {", "\t\t\tTU_build_infrastructure = yes", "\t\t}", "\t}", "}", ""]

    for n, (count, level) in enumerate(((1, 2), (2, 2), (3, 3)), 1):
        picks = []
        for k in range(count):
            picks.append("""		random_owned_controlled_state = {
			limit = {
				NOT = { has_state_flag = TU_fort_done }
				any_neighbor_state = { NOT = { is_owned_by = ROOT } }
			}
			set_state_flag = TU_fort_done
			add_building_construction = {
				type = bunker
				level = %d
				instant_build = yes
				province = { all_provinces = yes limit_to_border = yes }
			}
		}""" % level)
        body = "\n".join(picks)
        out.append("""TU_build_forts_%d = {
	custom_effect_tooltip = TU_build_forts_%d_tt
	hidden_effect = {
		if = {
			limit = {
				NOT = { any_owned_state = { is_controlled_by = ROOT any_neighbor_state = { NOT = { is_owned_by = ROOT } } } }
			}
			capital_scope = {
				add_building_construction = {
					type = bunker
					level = %d
					instant_build = yes
					province = { all_provinces = yes }
				}
			}
		}
%s
		every_owned_state = {
			limit = { has_state_flag = TU_fort_done }
			clr_state_flag = TU_fort_done
		}
	}
}
""" % (n, n, level, body))
        cpicks = []
        for k in range(count):
            cpicks.append("""		random_owned_controlled_state = {
			limit = {
				NOT = { has_state_flag = TU_fort_done }
				is_coastal = yes
			}
			set_state_flag = TU_fort_done
			add_building_construction = {
				type = coastal_bunker
				level = %d
				instant_build = yes
				province = { all_provinces = yes limit_to_coastal = yes }
			}
		}""" % level)
        out.append("""TU_build_coastal_forts_%d = {
	custom_effect_tooltip = TU_build_coastal_forts_%d_tt
	hidden_effect = {
		if = {
			limit = { NOT = { any_owned_state = { is_controlled_by = ROOT is_coastal = yes } } }
			TU_build_forts_%d = yes
		}
		else = {
%s
		}
		every_owned_state = {
			limit = { has_state_flag = TU_fort_done }
			clr_state_flag = TU_fort_done
		}
	}
}
""" % (n, n, n, "\n".join("\t" + l for l in "\n".join(cpicks).split("\n"))))

    OUT.write_text("\n".join(out), encoding="utf-8")
    text = OUT.read_text(encoding="utf-8")
    assert text.count("{") == text.count("}"), "brace mismatch"
    assert all(ord(c) < 128 for c in text)

    loc = {
        "TU_build_railway_tt": ("§Y철도§!: 수도에서 주요 도시까지 철도를 놓는다 (이미 있으면 한 단계 올린다).",
                                "§YRailways§!: lay railways from the capital to the main cities (upgrade by one level if they exist)."),
    }
    for n, (count, level) in enumerate(((1, 2), (2, 2), (3, 3)), 1):
        loc["TU_build_forts_%d_tt" % n] = ("§Y요새§!: 국경 주 %d곳의 국경 프로빈스에 육상 요새 %d단계 건설" % (count, level),
                                           "§YForts§!: build level %d land forts on the border provinces of %d border state(s)" % (level, count))
        loc["TU_build_coastal_forts_%d_tt" % n] = ("§Y해안 요새§!: 해안 주 %d곳의 해안 프로빈스에 해안 요새 %d단계 건설" % (count, level),
                                                   "§YCoastal Forts§!: build level %d coastal forts in %d coastal state(s)" % (level, count))
    for lang, idx in (("korean", 0), ("english", 1)):
        p = MOD / "localisation" / lang / ("tu_rail_fort_l_%s.yml" % lang)
        body = "l_%s:\n" % lang + "".join(' %s:0 "%s"\n' % (k, v[idx]) for k, v in loc.items())
        p.write_text("\ufeff" + body, encoding="utf-8")
    print("rail blocks:", len(blocks), "->", OUT.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
