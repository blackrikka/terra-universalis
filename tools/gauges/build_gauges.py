#!/usr/bin/env python3
"""국가별 '수치' 변수를 디시전 창에 막대로 보여 주는 '국가 현황' 분류를 만든다.

    python -I tools/gauges/build_gauges.py

나라마다 결정 없는 분류 TU_<태그>_status_category 를 하나 만들고(항상 보임), 거기에 scripted GUI 를 붙인다.
- 막대: 0~최댓값을 20칸(최댓값이 10 이하면 1칸 = 1)으로 나눠 채운다. 값은 변수에서 바로 읽으므로 기존 효과는 손대지 않는다.
- 최댓값은 clamp_variable 에서, 눈금(기준값)은 check_variable 비교값에서 자동으로 뽑는다 (내용이 바뀌면 다시 돌리면 됨).
- 마우스를 올리면 현재값·기준값 설명이 뜬다.

만드는 파일 (모두 생성물, 손으로 고치지 말 것):
  common/decisions/categories/tu_status_categories.txt
  common/scripted_guis/tu_status_scripted_gui.txt
  interface/tu_status.gui, interface/tu_status.gfx
  gfx/interface/tu_status/*.dds
  localisation/{korean,english}/tu_status_l_{korean,english}.yml
"""

import re
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MOD = REPO / "terra_universalis"
HEADER = "# Generated by tools/gauges/build_gauges.py - do not edit by hand.\n"

sys.path.insert(0, str(Path(__file__).resolve().parent))
from countries import COUNTRIES, ICONS  # noqa: E402  (나라별 제목·설명·수치 목록, countries.py)

COLORS = {"empty": 1, "gold": 2, "green": 3, "red": 4, "blue": 5}
RGB = {"gold": (212, 167, 60), "green": (104, 186, 108), "red": (210, 82, 70), "blue": (92, 148, 220)}

X0, W = 18, 470            # 패널 왼쪽, 전체 너비
HALF = (W - 10) // 2       # 반 칸 너비
ROW_H, ROW_GAP = 38, 4
BAR_Y, BAR_H, SEG_GAP = 23, 9, 2
MAX_SEGS = 20


# ---------------------------------------------------------------- 모드에서 최댓값·기준값 읽기

def scan_mod():
    clamps, checks = {}, {}
    for p in list((MOD / "common").rglob("*.txt")) + list((MOD / "events").rglob("*.txt")):
        t = p.read_text(encoding="utf-8-sig", errors="replace")
        if t.startswith(HEADER):        # 이 스크립트가 만든 파일은 건너뛴다
            continue
        for m in re.finditer(r"clamp_variable\s*=\s*\{\s*var\s*=\s*(\w+)\s+min\s*=\s*(-?[\d.]+)\s+max\s*=\s*(-?[\d.]+)", t):
            clamps.setdefault(m.group(1), set()).add((float(m.group(2)), float(m.group(3))))
        for m in re.finditer(r"check_variable\s*=\s*\{\s*(\w+)\s*([<>]=?|=)\s*(-?[\d.]+)\s*\}", t):
            checks.setdefault(m.group(1), set()).add(float(m.group(3)))
    return clamps, checks


def ticks_for(values, top):
    """비교값(>39, <41 …)을 5 단위 기준값으로 모은다."""
    out = set()
    for v in values:
        step = 5 if top > 10 else 1
        r = round(v / step) * step
        if 0 < r < top:
            out.add(int(r))
    return sorted(out)


# ---------------------------------------------------------------- 그림 (비압축 BGRA DDS)

def write_dds(path, w, h, pixel):
    hdr = b"DDS " + struct.pack("<7I", 124, 0x100F, h, w, w * 4, 0, 1) + b"\0" * 44
    hdr += struct.pack("<8I", 32, 0x41, 0, 32, 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000)
    hdr += struct.pack("<5I", 0x1000, 0, 0, 0, 0)
    buf = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b, a = pixel(x, y)
            buf += bytes((b, g, r, a))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(hdr + bytes(buf))


def rounded(w, h, rad, fill, border):
    def px(x, y):
        cx = min(max(x, rad), w - 1 - rad)
        cy = min(max(y, rad), h - 1 - rad)
        d = ((x - cx) ** 2 + (y - cy) ** 2) ** .5
        if d > rad + .5:
            return (0, 0, 0, 0)
        if d > rad - .7 or x == 0 or y == 0 or x == w - 1 or y == h - 1:
            return border
        return fill
    return px


def seg_strip(w):
    """한 칸 그림: 5프레임 (빈칸, 금, 초록, 빨강, 파랑)."""
    def px(x, y):
        f, lx = divmod(x, w)
        if f == 0:
            edge = lx == 0 or lx == w - 1 or y == 0 or y == BAR_H - 1
            return (78, 84, 98, 255) if edge else (34, 37, 46, 255)
        r, g, b = RGB[["gold", "green", "red", "blue"][f - 1]]
        k = 1.25 if y <= 1 else (0.78 if y >= BAR_H - 2 else 1.0)
        return (min(255, int(r * k)), min(255, int(g * k)), min(255, int(b * k)), 255)
    return px


def build_gfx(seg_widths):
    gdir = MOD / "gfx" / "interface" / "tu_status"
    for old in gdir.glob("*.dds") if gdir.is_dir() else []:
        old.unlink()
    write_dds(gdir / "row_full.dds", W, ROW_H, rounded(W, ROW_H, 5, (20, 22, 28, 215), (74, 80, 96, 255)))
    write_dds(gdir / "row_half.dds", HALF, ROW_H, rounded(HALF, ROW_H, 5, (20, 22, 28, 215), (74, 80, 96, 255)))
    write_dds(gdir / "tick.dds", 2, BAR_H + 6, lambda x, y: (240, 236, 220, 230))
    sprites = [("GFX_tu_status_row_full", "row_full.dds", 1), ("GFX_tu_status_row_half", "row_half.dds", 1),
               ("GFX_tu_status_tick", "tick.dds", 1)]
    for w in sorted(seg_widths):
        write_dds(gdir / ("seg_%d.dds" % w), w * 5, BAR_H, seg_strip(w))
        sprites.append(("GFX_tu_status_seg_%d" % w, "seg_%d.dds" % w, 5))
    lines = [HEADER, "spriteTypes = {"]
    for name, f, frames in sprites:
        lines += ["\tspriteType = {", '\t\tname = "%s"' % name,
                  '\t\ttexturefile = "gfx/interface/tu_status/%s"' % f]
        if frames > 1:
            lines.append("\t\tnoOfFrames = %d" % frames)
        lines.append("\t}")
    lines.append("}")
    (MOD / "interface" / "tu_status.gfx").write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---------------------------------------------------------------- 배치

def layout(gauges):
    """막대가 긴 것은 한 줄, 작은 칸(10 이하)과 숫자는 반 줄씩 짝지어 놓는다."""
    full = [g for g in gauges if g["kind"] == "bar" and g["max"] > 10]
    small = [g for g in gauges if g not in full]
    rows = [[g] for g in full] + [small[i:i + 2] for i in range(0, len(small), 2)]
    y = 0
    for row in rows:
        width = W if len(row) == 1 and row[0] in full else HALF
        for i, g in enumerate(row):
            g.update(x=X0 + i * (HALF + 10), y=y, w=width)
        y += ROW_H + ROW_GAP
    return y


def segs(g):
    n = int(g["max"]) if g["max"] <= 10 else MAX_SEGS
    bw = g["w"] - 16
    sw = (bw - SEG_GAP * (n - 1)) // n
    return n, sw


def esc(s):
    return s.replace('"', "'")


def build():
    clamps, checks = scan_mod()
    seg_widths = set()
    cats, guis, sgui = [HEADER], [HEADER, "guiTypes = {"], [HEADER, "scripted_gui = {"]
    loc = {"korean": [], "english": []}
    for tag, title, desc, gauges in COUNTRIES:
        for g in gauges:
            g.setdefault("kind", "bar")
            if "max" not in g and g["kind"] == "bar":
                rng = clamps.get(g["var"])
                if not rng:
                    sys.exit("최댓값을 알 수 없음 (clamp_variable 없음): %s — max= 를 적어 주세요" % g["var"])
                g["max"] = max(r[1] for r in rng)
            g.setdefault("max", 0)
            g["ticks"] = ticks_for(checks.get(g["var"], ()), g["max"]) if g["kind"] == "bar" else []
        height = layout(gauges) + 4
        cat = "TU_%s_status_category" % tag
        ui = "TU_%s_status_ui" % tag
        win = "TU_%s_status_window" % tag
        cats += ["%s = {" % cat, "\ticon = %s" % ICONS.get(tag, "GFX_decision_category_generic_political_actions"), "\tpriority = 300",
                 "\tvisible_when_empty = yes", "\tallowed = { original_tag = %s }" % tag,
                 "\tscripted_gui = %s" % ui, "}", ""]
        trig = []
        guis += ["\tcontainerWindowType = {", '\t\tname = "%s"' % win, "\t\tposition = { x = 0 y = 0 }",
                 "\t\tsize = { width = 100%% height = %d }" % height, ""]
        for g in gauges:
            key = "TU_STATUS_%s" % g["var"]
            el = "tu_st_%s" % g["var"].lower()
            x, y, w = g["x"], g["y"], g["w"]
            guis += ["\t\ticonType = {", '\t\t\tname = "%s_bg"' % el,
                     '\t\t\tspriteType = "GFX_tu_status_row_%s"' % ("full" if w == W else "half"),
                     "\t\t\tposition = { x = %d y = %d }" % (x, y), "\t\t}"]
            ty = y + (4 if g["kind"] == "bar" else 11)
            vw = 100 if w == W or g["kind"] == "number" else 64
            guis += text_box(el + "_label", x + 8, ty, w - 20 - vw, key + "_label", "left")
            guis += text_box(el + "_value", x + w - 8 - vw, ty, vw, key + "_value", "right")
            if g["kind"] == "bar":
                n, sw = segs(g)
                seg_widths.add(sw)
                bx = x + 8
                for i in range(n):
                    sx = bx + i * (sw + SEG_GAP)
                    for state in ("e", "f"):
                        guis += ["\t\ticonType = {", '\t\t\tname = "%s_%s%02d"' % (el, state, i + 1),
                                 '\t\t\tspriteType = "GFX_tu_status_seg_%d"' % sw,
                                 "\t\t\tframe = %d" % (COLORS["empty"] if state == "e" else COLORS[g["color"]]),
                                 "\t\t\tposition = { x = %d y = %d }" % (sx, y + BAR_Y), "\t\t}"]
                    # i 번째 칸은 값이 그 칸의 절반을 넘으면 채운다
                    th = g["max"] * (i + 0.5) / n
                    trig.append("\t\t\t%s_f%02d_visible = { check_variable = { %s > %s } }" % (el, i + 1, g["var"], fmt(th)))
                span = n * sw + (n - 1) * SEG_GAP
                for t in g["ticks"] if g["max"] > 10 else []:
                    tx = bx + round(span * t / g["max"]) - 1
                    guis += ["\t\ticonType = {", '\t\t\tname = "%s_t%d"' % (el, t), '\t\t\tspriteType = "GFX_tu_status_tick"',
                             "\t\t\tposition = { x = %d y = %d }" % (tx, y + BAR_Y - 3), "\t\t}"]
            # 마우스 올림 설명 (보이지 않는 글상자)
            guis += ["\t\tinstantTextBoxType = {", '\t\t\tname = "%s_tip"' % el, "\t\t\tposition = { x = %d y = %d }" % (x, y),
                     "\t\t\tmaxWidth = %d" % w, "\t\t\tmaxHeight = %d" % ROW_H, '\t\t\ttext = ""',
                     "\t\t\tpdx_tooltip = %s_tt" % key, "\t\t}", ""]
            for lang, name in (("korean", g["ko"]), ("english", g["en"])):
                loc[lang] += loc_lines(lang, key, g, name)
        guis.append("\t}")
        sgui += ["\t%s = {" % ui, "\t\tcontext_type = decision_category", '\t\twindow_name = "%s"' % win]
        if trig:
            sgui += ["\t\ttriggers = {"] + trig + ["\t\t}"]
        sgui += ["\t}"]
        for i, lang in enumerate(("korean", "english")):
            loc[lang] += [' %s:0 "%s"' % (cat, esc(title[i])), ' %s_desc:0 "%s"' % (cat, esc(desc[i]))]
    guis.append("}")
    sgui.append("}")

    write(MOD / "common/decisions/categories/tu_status_categories.txt", "\n".join(cats))
    write(MOD / "common/scripted_guis/tu_status_scripted_gui.txt", "\n".join(sgui) + "\n")
    write(MOD / "interface/tu_status.gui", "\n".join(guis) + "\n")
    build_gfx(seg_widths)
    for lang, lines in loc.items():
        p = MOD / "localisation" / lang / ("tu_status_l_%s.yml" % lang)
        p.write_text("\ufeffl_%s:\n" % lang + "\n".join(lines) + "\n", encoding="utf-8")
    n = sum(len(c[3]) for c in COUNTRIES)
    print("국가 현황: %d개국, 수치 %d개" % (len(COUNTRIES), n))


def fmt(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def text_box(name, x, y, w, key, align):
    return ["\t\tinstantTextBoxType = {", '\t\t\tname = "%s"' % name, "\t\t\tposition = { x = %d y = %d }" % (x, y),
            '\t\t\tfont = "hoi_16mbs"', "\t\t\tmaxWidth = %d" % w, "\t\t\tmaxHeight = 18",
            '\t\t\ttext = "%s"' % key, "\t\t\tformat = %s" % align, "\t\t\tfixedsize = yes", "\t\t}"]


def loc_lines(lang, key, g, name):
    v = "[?%s|Y0]" % g["var"]
    if "value" in g:
        val = g["value"][0 if lang == "korean" else 1].format(v=v)
    elif g.get("cap"):
        val = "%s / [?%s|0]" % (v, g["cap"])
    elif g["kind"] == "bar":
        val = "%s / %s" % (v, fmt(g["max"]))
    else:
        val = v
    out = [' %s_label:0 "%s"' % (key, esc(name)), ' %s_value:0 "%s"' % (key, val)]
    ko = lang == "korean"
    tip = "§Y%s§!: %s" % (esc(name), val)
    if g.get("tip"):
        tip += "\\n" + esc(g["tip"][0 if ko else 1])
    if g.get("cap"):
        tip += "\\n" + ("레벨 상한은 발전소 레벨 + 2입니다." if ko else "Level cap: Power Plant level + 2.")
    if g["ticks"]:
        marks = " · ".join(str(t) for t in g["ticks"])
        tip += "\\n\\n" + ("§g막대의 눈금(%s)은 정세가 달라지는 고비입니다.§!" % marks if ko
                           else "§gThe marks on the bar (%s) are turning points.§!" % marks)
    out.append(' %s_tt:0 "%s"' % (key, tip))
    return out


def write(p, text):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")


if __name__ == "__main__":
    build()
